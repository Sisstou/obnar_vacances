import { supabase, supabaseConfigured } from '../lib/supabase';
import { toAppError } from '../lib/errors';
import { err, ok, type AppResult } from '../lib/result';
import {
  getStorageBucketPolicy,
  validateStorageUpload,
  type StorageBucket,
} from './file-lifecycle';

export interface StorageUploadInput {
  bucket: StorageBucket;
  path: string;
  body: ArrayBuffer | Uint8Array;
  contentType: string;
  sizeBytes: number;
  cacheControlSeconds?: number;
}

export interface StoredObject {
  bucket: StorageBucket;
  path: string;
  fullPath: string;
}

function unavailable<T>(): AppResult<T> {
  return err({
    code: 'supabase_not_configured',
    message: 'إعدادات الاتصال بالخدمة غير مكتملة.',
    retryable: false,
  });
}

/**
 * Uploads a new object without overwriting an existing one.
 * Versioned paths should be generated by file-lifecycle.ts.
 * Authorization remains enforced by Supabase Storage RLS policies.
 */
export async function uploadStorageObject(
  input: StorageUploadInput,
): Promise<AppResult<StoredObject>> {
  if (!supabaseConfigured) return unavailable();

  const validation = validateStorageUpload(input);
  if (!validation.ok) return validation;

  const { data, error } = await supabase.storage
    .from(input.bucket)
    .upload(input.path, input.body, {
      contentType: input.contentType,
      cacheControl: String(
        Math.min(Math.max(input.cacheControlSeconds ?? 3600, 60), 86400),
      ),
      upsert: false,
    });

  if (error) return err(toAppError(error, 'تعذر رفع الملف.'));
  return ok({
    bucket: input.bucket,
    path: data.path,
    fullPath: data.fullPath,
  });
}

/**
 * Creates a short-lived URL for a private Storage object.
 * Never use getPublicUrl for these private buckets.
 */
export async function createStorageSignedUrl(
  bucket: StorageBucket,
  path: string,
  expiresInSeconds = 300,
): Promise<AppResult<string>> {
  if (!supabaseConfigured) return unavailable();

  if (!path.trim() || path.startsWith('/') || path.split('/').some((part) => !part || part === '.' || part === '..')) {
    return err({
      code: 'invalid_storage_path',
      message: 'مسار الملف غير صالح.',
      retryable: false,
    });
  }

  const policy = getStorageBucketPolicy(bucket);
  if (!policy) {
    return err({
      code: 'unsupported_storage_bucket',
      message: 'حاوية الملفات غير مدعومة.',
      retryable: false,
    });
  }

  const ttl = Math.min(Math.max(Math.floor(expiresInSeconds), 60), 3600);
  const { data, error } = await supabase.storage
    .from(bucket)
    .createSignedUrl(path, ttl);

  if (error) return err(toAppError(error, 'تعذر إنشاء رابط آمن للملف.'));
  return ok(data.signedUrl);
}

import React from 'react';
import {
  Image,
  ScrollView,
  StyleSheet,
  Text,
  View,
  type StyleProp,
  type ViewStyle,
} from 'react-native';

export type ExploreLocalAreaLocale = 'ar' | 'fr';

export interface LocalAreaItem {
  id: string;
  title: string;
  description?: string;
  imageUrl?: string | null;
}

export interface ExploreLocalAreaProps {
  locale?: ExploreLocalAreaLocale;
  items: LocalAreaItem[];
  title?: string;
  style?: StyleProp<ViewStyle>;
}

/**
 * Horizontal local-discovery presentation.
 * The parent supplies verified place names, descriptions, and image URLs.
 * No location claims or remote data are generated by this component.
 */
export function ExploreLocalArea({
  locale = 'ar',
  items,
  title,
  style,
}: ExploreLocalAreaProps) {
  const isArabic = locale === 'ar';
  const sectionTitle = title ?? (isArabic ? 'اكتشف المنطقة' : 'Découvrez la région');
  const emptyText = isArabic
    ? 'ستظهر الأماكن بعد توفير معلومات موثوقة عنها.'
    : 'Les lieux apparaîtront lorsque des informations fiables seront disponibles.';

  return (
    <View style={[styles.container, { direction: isArabic ? 'rtl' : 'ltr' }, style]}>
      <Text style={[styles.heading, { textAlign: isArabic ? 'right' : 'left' }]}>
        {sectionTitle}
      </Text>
      {items.length === 0 ? (
        <View style={styles.empty}>
          <Text style={styles.emptyText}>{emptyText}</Text>
        </View>
      ) : (
        <ScrollView
          horizontal
          showsHorizontalScrollIndicator={false}
          contentContainerStyle={styles.list}
        >
          {items.map((item) => (
            <View key={item.id} style={styles.card}>
              {item.imageUrl ? (
                <Image
                  source={{ uri: item.imageUrl }}
                  style={styles.image}
                  resizeMode="cover"
                  accessible
                  accessibilityRole="image"
                  accessibilityLabel={item.title}
                />
              ) : (
                <View style={styles.imageFallback}>
                  <Text style={styles.imageGlyph}>⌖</Text>
                  <Text style={styles.imageFallbackText}>
                    {isArabic ? 'الصورة غير متوفرة' : 'Image indisponible'}
                  </Text>
                </View>
              )}
              <View style={styles.copy}>
                <Text numberOfLines={2} style={styles.itemTitle}>{item.title}</Text>
                {item.description ? (
                  <Text numberOfLines={3} style={styles.description}>
                    {item.description}
                  </Text>
                ) : null}
              </View>
            </View>
          ))}
        </ScrollView>
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  container: {
    gap: 12,
  },
  heading: {
    color: '#123B5D',
    fontSize: 19,
    lineHeight: 27,
    fontWeight: '900',
  },
  list: {
    gap: 12,
    paddingVertical: 2,
  },
  card: {
    width: 232,
    overflow: 'hidden',
    borderWidth: 1,
    borderColor: '#E8E0D2',
    borderRadius: 17,
    backgroundColor: '#FFFFFF',
  },
  image: {
    width: '100%',
    height: 132,
    backgroundColor: '#F2EEE6',
  },
  imageFallback: {
    height: 132,
    alignItems: 'center',
    justifyContent: 'center',
    gap: 5,
    backgroundColor: '#F2EEE6',
  },
  imageGlyph: {
    color: '#A47B36',
    fontSize: 28,
  },
  imageFallbackText: {
    color: '#786B57',
    fontSize: 11,
  },
  copy: {
    gap: 6,
    padding: 12,
  },
  itemTitle: {
    color: '#344054',
    fontSize: 15,
    lineHeight: 21,
    fontWeight: '800',
    textAlign: 'auto',
  },
  description: {
    color: '#667085',
    fontSize: 12,
    lineHeight: 18,
    textAlign: 'auto',
  },
  empty: {
    minHeight: 88,
    justifyContent: 'center',
    padding: 16,
    borderWidth: 1,
    borderColor: '#E8E0D2',
    borderRadius: 15,
    backgroundColor: '#FFFFFF',
  },
  emptyText: {
    color: '#667085',
    fontSize: 13,
    lineHeight: 20,
    textAlign: 'center',
  },
});
